import 'package:equatable/equatable.dart';

/// Canonical wire types with legacy read/source compatibility.
enum NotificationType {
  general,
  repairBooking,
  repairStatus,
  warranty,
  device,
  promotion,
  system;

  // Source compatibility for existing domain event writers.
  static const repairConfirmed = repairBooking;
  static const repairCompleted = repairStatus;
  static const warrantyExpiring = warranty;

  List<String> get readAliases => switch (this) {
        repairBooking => ['repair_booking', 'repairBooking', 'repairConfirmed'],
        repairStatus => ['repair_status', 'repairStatus', 'repairCompleted'],
        warranty => ['warranty', 'warrantyExpiring'],
        _ => [wireValue],
      };
  String get wireValue => switch (this) {
        repairBooking => 'repair_booking',
        repairStatus => 'repair_status',
        _ => name,
      };
  String get displayName => switch (this) {
        general => 'Thông báo chung',
        repairBooking => 'Đặt lịch sửa chữa',
        repairStatus => 'Trạng thái sửa chữa',
        warranty => 'Bảo hành',
        device => 'Thiết bị',
        promotion => 'Khuyến mãi',
        system => 'Hệ thống',
      };
  static NotificationType fromName(String? value) => switch (value) {
        'repair_booking' ||
        'repairBooking' ||
        'repairConfirmed' =>
          repairBooking,
        'repair_status' || 'repairStatus' || 'repairCompleted' => repairStatus,
        'warranty' || 'warrantyExpiring' => warranty,
        'device' => device,
        'promotion' => promotion,
        'system' => system,
        _ => general,
      };
}

/// A record that a customer-facing notification was generated by the
/// system — the domain source of truth this sprint implements.
///
/// This is deliberately NOT a push-delivery record: there is no `sentAt`/
/// `deliveryStatus` field implying an FCM push actually reached a device,
/// because no such delivery mechanism exists in this repository (no Cloud
/// Functions, no FCM Admin SDK call, no Customer App integration — see the
/// Sprint 14 report). `readAt` only tracks in-app read state within
/// whichever application displays this record (currently: the CMS
/// Notification Center).
class NotificationEntity extends Equatable {
  final String id;
  final NotificationType type;
  final String title;
  final String body;
  final String customerId;
  final String customerName;
  final String? targetType;
  final String? targetId;
  final String? createdBy;
  final DateTime createdAt;
  final DateTime? readAt;

  const NotificationEntity({
    required this.id,
    required this.type,
    required this.title,
    required this.body,
    required this.customerId,
    required this.customerName,
    this.targetType,
    this.targetId,
    this.createdBy,
    required this.createdAt,
    this.readAt,
  });

  bool get isRead => readAt != null;

  NotificationEntity copyWith({
    String? id,
    NotificationType? type,
    String? title,
    String? body,
    String? customerId,
    String? customerName,
    String? targetType,
    String? targetId,
    String? createdBy,
    DateTime? createdAt,
    DateTime? readAt,
  }) {
    return NotificationEntity(
      id: id ?? this.id,
      type: type ?? this.type,
      title: title ?? this.title,
      body: body ?? this.body,
      customerId: customerId ?? this.customerId,
      customerName: customerName ?? this.customerName,
      targetType: targetType ?? this.targetType,
      targetId: targetId ?? this.targetId,
      createdBy: createdBy ?? this.createdBy,
      createdAt: createdAt ?? this.createdAt,
      readAt: readAt ?? this.readAt,
    );
  }

  @override
  List<Object?> get props => [
        id,
        type,
        title,
        body,
        customerId,
        customerName,
        targetType,
        targetId,
        createdBy,
        createdAt,
        readAt,
      ];
}
